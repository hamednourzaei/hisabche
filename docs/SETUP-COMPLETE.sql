-- ============================================================================
-- SELF-CHECK
--
-- Runs automatically at the end. Read it before you close the tab.
-- ============================================================================

DO $final$
DECLARE
  v_tables    integer;
  v_policies  integer;
  v_rls_off   integer;
  v_functions integer;
  v_indexes   integer;
  v_fks       integer;
BEGIN
  SELECT count(*) INTO v_tables
    FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE';

  SELECT count(*) INTO v_policies FROM pg_policies WHERE schemaname = 'public';

  -- A tenant table with RLS off is readable by anyone holding the anon key.
  -- This is the single most important number on the page.
  SELECT count(*) INTO v_rls_off
    FROM pg_tables t
    WHERE t.schemaname = 'public'
      AND NOT t.rowsecurity
      AND EXISTS (
        SELECT 1 FROM information_schema.columns c
        WHERE c.table_schema = 'public'
          AND c.table_name = t.tablename
          AND c.column_name = 'workspace_id'
      );

  SELECT count(*) INTO v_functions
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind = 'f';

  SELECT count(*) INTO v_indexes FROM pg_indexes WHERE schemaname = 'public';

  SELECT count(*) INTO v_fks
    FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace
    WHERE n.nspname = 'public' AND c.contype = 'f';

  RAISE NOTICE '';
  RAISE NOTICE '════════════════════════════════════════════';
  RAISE NOTICE '  tables        %', v_tables;
  RAISE NOTICE '  functions     %', v_functions;
  RAISE NOTICE '  policies      %', v_policies;
  RAISE NOTICE '  indexes       %', v_indexes;
  RAISE NOTICE '  foreign keys  %', v_fks;
  RAISE NOTICE '════════════════════════════════════════════';

  IF v_rls_off > 0 THEN
    RAISE WARNING '% tenant table(s) have workspace_id and RLS OFF — anyone with the anon key can read them. Run the query below.', v_rls_off;
  ELSE
    RAISE NOTICE '  ✅ every workspace_id table has RLS on';
  END IF;

  RAISE NOTICE '';
  RAISE NOTICE '  Next: docs/_verify-after.sql, then docs/_verify-rls.sql';
  RAISE NOTICE '';
END
$final$;

-- Any row here is a tenant table left open. Expect none.
SELECT t.tablename AS tenant_table_with_rls_off
FROM pg_tables t
WHERE t.schemaname = 'public'
  AND NOT t.rowsecurity
  AND EXISTS (
    SELECT 1 FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.table_name = t.tablename
      AND c.column_name = 'workspace_id'
  )
ORDER BY 1;
