/**
 * Assigns one of the 13 viral templates deterministically across all reels.
 * Uses a prime coprimality stride (step = 5) modulo 13 (gcd(5, 13) = 1) so consecutive reels
 * never repeat the same template, ensuring maximum diversity across the catalog.
 */
export function getReelViralTemplate(reelId: string): ViralTemplateId {
  const num = parseInt(reelId, 10)
  if (isNaN(num)) {
    return 'tactile-train-scroll'
  }
  // Co-prime stride formula: ((num - 1) * 5) % 13 guarantees a full 13-cycle without repeats
  const idx = ((num - 1) * 5) % VIRAL_TEMPLATE_LIST.length
  return VIRAL_TEMPLATE_LIST[idx]!
}

export function getTemplateMetadata(id: ViralTemplateId): TemplateMetadata {
  const meta = VIRAL_TEMPLATES[id]
  if (!meta) {
    throw new Error(`Template '${id}' not found in VIRAL_TEMPLATES catalog.`)
  }
  return meta
}
