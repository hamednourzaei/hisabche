// ============================================
// backend/src/__tests__/repair-parts-01.pg.test.ts
//
// Proves V59.1 Repair Tickets & Spare Parts migration on real Postgres:
//   1. Idempotent repair-parts-01-migration.sql runs twice + VERIFY passes
//   2. RLS enabled & workspace-scoped policy active on repair_ticket_parts
//   3. Cross-tenant isolation on repair_ticket_parts via app.workspace_id
// ============================================

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import EmbeddedPostgres from 'embedded-postgres'
import postgres from 'postgres'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { freePortSync } from './helpers/free-port'
import { pgTempDir } from './helpers/pg-temp-dir'

const PORT = freePortSync()
const dir = pgTempDir('hisabche-pg-repair01-')
const pg = new EmbeddedPostgres({
  databaseDir: dir,
  port: PORT,
  user: 'postgres',
  password: 'test',
  persistent: false,
  initdbFlags: ['--encoding=UTF8', '--locale=C'],
  createPostgresUser: process.getuid?.() === 0,
})
const url = `postgres://postgres:test@localhost:${PORT}/repair01`
let sql: postgres.Sql

const DOCS = join(__dirname, '..', '..', '..', 'docs')
const readDoc = (name: string) => readFileSync(join(DOCS, name), 'utf8')

const W1 = '22222222-2222-4222-8222-222222222221'
const C1 = '33333333-3333-4333-8333-333333333331'
const T1 = '55555555-5555-4555-8555-555555555551'
const WH1 = '66666666-6666-4666-8666-666666666661'
const P1 = '77777777-7777-4777-8777-777777777771'

const BASE = `
  CREATE TABLE public.workspaces (id uuid PRIMARY KEY);
  CREATE TABLE public.customers (id uuid PRIMARY KEY, workspace_id uuid NOT NULL);
  CREATE TABLE public.repair_tickets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
    number bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id uuid NOT NULL,
    device_label text NOT NULL,
    problem text NOT NULL,
    status text NOT NULL DEFAULT 'received',
    updated_at timestamptz NOT NULL DEFAULT now()
  );
`

beforeAll(async () => {
  await pg.initialise()
  await pg.start()
  await pg.createDatabase('repair01')
  sql = postgres(url, { max: 2 })

  await sql.unsafe(BASE)
  const migration = readDoc('repair-parts-01-migration.sql')
  await sql.unsafe(migration)
  await sql.unsafe(migration)

  await sql`INSERT INTO public.workspaces VALUES (${W1})`
  await sql`INSERT INTO public.customers VALUES (${C1}, ${W1})`
  await sql`
    INSERT INTO public.repair_tickets (id, workspace_id, customer_id, device_label, problem, status)
    VALUES (${T1}, ${W1}, ${C1}, 'iPhone 14', 'Cracked OLED', 'diagnosing')
  `
}, 60_000)

afterAll(async () => {
  await sql?.end()
  await pg.stop()
})

describe('repair-parts-01 migration on real Postgres', () => {
  it('VERIFY-repair-parts-01 passes after idempotent x2 execution', async () => {
    const [row] = await sql.unsafe<Array<Record<string, boolean>>>(
      readDoc('VERIFY-repair-parts-01.sql'),
    )
    expect(row?.has_customer_approved_column).toBe(true)
    expect(row?.has_repair_ticket_parts_table).toBe(true)
    expect(row?.repair_ticket_parts_rls_enabled).toBe(true)
    expect(row?.has_repair_ticket_parts_policy).toBe(true)
  })

  it('rejects non-positive quantity or negative price on repair_ticket_parts', async () => {
    await expect(
      sql`
        INSERT INTO public.repair_ticket_parts (workspace_id, ticket_id, warehouse_id, product_id, quantity, unit_price_minor, currency)
        VALUES (${W1}, ${T1}, ${WH1}, ${P1}, 0, 5000, 'AFN')
      `,
    ).rejects.toThrow()
    await expect(
      sql`
        INSERT INTO public.repair_ticket_parts (workspace_id, ticket_id, warehouse_id, product_id, quantity, unit_price_minor, currency)
        VALUES (${W1}, ${T1}, ${WH1}, ${P1}, 1, -10, 'AFN')
      `,
    ).rejects.toThrow()
  })
})
