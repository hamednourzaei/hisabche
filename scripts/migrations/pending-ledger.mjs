#!/usr/bin/env node
// ============================================
// scripts/migrations/pending-ledger.mjs
//
// The canonical migration ledger: `docs/MIGRATIONS-PENDING.md` (V64 §16).
//
// WHAT THIS FILE CAN AND CANNOT KNOW. Which migration the live database has
// already received lives in the database, not in the working tree. This script
// therefore never guesses an applied/unapplied status: every row is written as
// `PENDING HUMAN CONFIRMATION`, and §3 carries the read-only query the owner
// runs to turn that into a real answer.
//
// WHAT IT CAN PROVE, from the tree: every `docs/*-migration.sql` file exists,
// appears exactly once, and has (or lacks) a `VERIFY-*` companion, a
// `FINDING-*` companion query, and a `*.pg.test.ts` that runs it on a real
// Postgres. Those gaps are the actionable part.
//
// The order in the table is deterministic (filename), NOT a dependency order.
// Within one family the `-NN` suffix is the order of its parts.
//
//   node scripts/migrations/pending-ledger.mjs           # write
//   node scripts/migrations/pending-ledger.mjs --check   # fail when stale
// ============================================

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { formatMarkdown } from '../lib/format-markdown.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const CHECK_ONLY = process.argv.includes('--check')
const OUT = 'docs/MIGRATIONS-PENDING.md'
const PENDING = 'PENDING HUMAN CONFIRMATION'

const docs = readdirSync(path.join(ROOT, 'docs'))
const testsDir = path.join(ROOT, 'backend', 'src', '__tests__')
const testFiles = readdirSync(testsDir).filter((name) => name.endsWith('.pg.test.ts'))

// The test file bodies are read once: a test can name a migration it does not
// share a name with (several run `base-schema-migration.sql` first), and the
// mention is stronger evidence than the filename alone.
const testBodies = new Map(
  testFiles.map((name) => [name, readFileSync(path.join(testsDir, name), 'utf8')]),
)

const migrations = docs.filter((name) => name.endsWith('-migration.sql')).sort()

const rows = migrations.map((file, index) => {
  const base = file.slice(0, -'-migration.sql'.length)
  const sequence = /-(\d{2})$/.exec(base)?.[1] ?? null
  const verify = docs.includes(`VERIFY-${base}.sql`) ? `VERIFY-${base}.sql` : null
  const finding = docs.includes(`FINDING-${base}.sql`) ? `FINDING-${base}.sql` : null
  // Convention first; then any test whose text names the file.
  const byName = testFiles.includes(`${base}.pg.test.ts`) ? `${base}.pg.test.ts` : null
  const byMention = byName ?? testFiles.find((name) => testBodies.get(name)?.includes(file)) ?? null
  return { index: index + 1, file, base, sequence, verify, finding, pgTest: byMention }
})

const missingVerify = rows.filter((row) => !row.verify)
const missingTest = rows.filter((row) => !row.pgTest)

const cell = (value) => (value === null ? '—' : `\`${value}\``)

const lines = [
  '# Migrations — the canonical ledger',
  '',
  '<!-- GENERATED by scripts/migrations/pending-ledger.mjs — do not edit by hand. -->',
  '',
  `Inventory taken from \`docs/*-migration.sql\`: **${rows.length}** files.`,
  '',
  '## 1. What «status» means here',
  '',
  'Every row says `' + PENDING + '`.',
  '',
  'That is not a placeholder for «probably applied». Which migration a database has received is',
  'recorded inside that database (`supabase_migrations.schema_migrations`), and this repository has no',
  'credentials for it and is forbidden to write to it. A ledger that guessed would be worse than none,',
  'because a guess is indistinguishable from a fact six months later.',
  '',
  '## 2. How to turn it into a real answer',
  '',
  'Run this once, read-only, against the project:',
  '',
  '```sql',
  'select version, name, inserted_at',
  'from supabase_migrations.schema_migrations',
  'order by version;',
  '```',
  '',
  'Any file below whose version is absent from that result is genuinely unapplied and must be treated as',
  '`' + PENDING + '`. Record the result next to this file rather than editing this table by hand.',
  '',
  '## 3. Order',
  '',
  'The table is sorted by filename so the file is deterministic and diffable. **That is not a dependency',
  'order.** The real order a database saw is the `inserted_at` of the query above. Within one family the',
  '`-NN` suffix is the order of its parts; a file with no suffix is a whole-domain migration.',
  '',
  '## 4. Gaps this inventory can prove',
  '',
  `| Gap | Count | Meaning |`,
  `| --- | --- | --- |`,
  `| Migration without a \`VERIFY-*\` file | ${missingVerify.length} | nobody can confirm it landed correctly |`,
  `| Migration without a \`*.pg.test.ts\` | ${missingTest.length} | it has never been executed on a real Postgres by the suite |`,
  '',
]

if (missingVerify.length > 0) {
  lines.push('Files with no verification query:', '')
  for (const row of missingVerify) lines.push(`- \`${row.file}\``)
  lines.push('')
}

if (missingTest.length > 0) {
  lines.push('Files with no PostgreSQL test:', '')
  for (const row of missingTest) lines.push(`- \`${row.file}\``)
  lines.push('')
}

lines.push(
  '## 5. Inventory',
  '',
  '| # | Migration | Seq | VERIFY | FINDING | PG test | Status |',
  '| --- | --- | --- | --- | --- | --- | --- |',
)
for (const row of rows) {
  lines.push(
    `| ${row.index} | \`${row.file}\` | ${row.sequence ?? '—'} | ${cell(row.verify)} | ${cell(row.finding)} | ${cell(row.pgTest)} | ${PENDING} |`,
  )
}

lines.push(
  '',
  '## 6. What V65 itself changed in the persisted shape',
  '',
  '**V65 produced zero migrations.** It added four new *answer keys* to the operational profile —',
  '`branches`, `warehouses`, and the derived topologies `MULTI_BRANCH` / `WAREHOUSE_NETWORK` — plus',
  '`tradeKeys` / `primaryTradeKey` on the inference input, which is never persisted.',
  '',
  'The persisted artefact is `public.workspaces.operational_dna`, a `jsonb` column whose only checks are',
  "`jsonb_typeof(...) = 'object'` and `pg_column_size(...) < 4096`, and whose single writer validates",
  'nothing beyond that. Adding keys needs no DDL. The largest profile the code can now produce — all 67',
  'registered activities at once — serialises to 862 bytes, 21% of the limit.',
  '',
  'The four-band business size V64 §5.1 asks for (`solo / 2-5 / 6-20 / more`, measured in headcount)',
  'also needs no migration: `docs/onboarding-server-state-migration.sql:27` declares `store_size` as',
  'plain `text` with no CHECK. It is not implemented because mapping the existing `small|medium|large`',
  'rows onto the four bands is an owner decision, not because of the schema.',
  '',
)

const target = path.join(ROOT, OUT)
const content = await formatMarkdown(target, lines.join('\n'))

if (CHECK_ONLY) {
  let current = null
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    current = null
  }
  if (current !== content) {
    console.error(`STALE: run node scripts/migrations/pending-ledger.mjs`)
    process.exit(1)
  }
  console.log(
    `OK: ${rows.length} migrations · ${rows.length - missingVerify.length} with VERIFY · ${rows.length - missingTest.length} with a PG test`,
  )
} else {
  writeFileSync(target, content)
  console.log(
    `Wrote ${OUT}: ${rows.length} migrations · ${rows.length - missingVerify.length} with VERIFY · ${rows.length - missingTest.length} with a PG test`,
  )
}
