function verifyChains() {
  const problems = []
  for (const flow of FLOW_CHAINS) {
    for (const [label, file, line, must] of flow.chain) {
      const full = path.join(ROOT, file)
      if (!fs.existsSync(full)) {
        problems.push(`${flow.id}: ${label} file missing: ${file}`)
        continue
      }
      const lines = fs.readFileSync(full, 'utf8').split('\n')
      const text = lines[line - 1] ?? ''
      if (must && !text.includes(must)) {
        problems.push(`${flow.id}: ${label} ${file}:${line} does not contain "${must}"`)
      }
    }
    for (const [file, needle] of flow.absent) {
      const full = path.join(ROOT, file)
      if (fs.existsSync(full) && fs.readFileSync(full, 'utf8').includes(needle)) {
        problems.push(`${flow.id}: ${file} unexpectedly contains ${needle}`)
      }
    }
  }
  if (problems.length > 0) {
    console.error('FLOW CHAIN VERIFICATION FAILED:')
    for (const p of problems) console.error(`  - ${p}`)
    process.exit(1)
  }
}
verifyChains()

