function decide(routeLike) {
  const key = `${routeLike.method} ${routeLike.path}`
  for (const rule of GAP_RULES) {
    if (rule.match.test(key) || rule.match.test(routeLike.path)) {
      return { tier: rule.tier, decision: rule.decision, hub: rule.hub, reason: rule.reason }
    }
  }
  return {
    tier: DOMAIN_TIER[routeLike.domain] || 'C',
    decision: 'NEEDS_OWNER_DECISION',
    hub: 'unassigned',
    reason: 'no classification rule matched this route',
  }
}

