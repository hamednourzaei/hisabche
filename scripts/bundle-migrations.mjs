#!/usr/bin/env node
// ============================================================================
// scripts/bundle-migrations.mjs
//
// Concatenate every migration, in the order `run-migrations.mjs` would apply
// them, into one file that can be pasted into the Supabase SQL Editor.
//
// ---------------------------------------------------------------------------
// WHY THIS EXISTS
//
// On the Supabase free plan the direct database host has no IPv4 address, so
// a machine without IPv6 cannot connect at all and `run-migrations.mjs
// --apply` never reaches the database. The SQL Editor runs inside the browser
// against Supabase's own network, which sidesteps the problem entirely.
//
// ---------------------------------------------------------------------------
// WHAT IS LOST BY GOING THIS WAY
//
// Said plainly, because it matters:
//
//   · No `schema_migrations` ledger. Nothing records what ran, so the next
//     person cannot tell what state the database is in. This script writes the
//     ledger inserts at the end to keep that from being true.
//   · No per-file transaction. The editor runs the whole thing as one script;
//     a failure part-way leaves the earlier statements applied.
//   · No checksum check, so an edited migration can be re-run silently.
//
// Prefer `run-migrations.mjs --apply` through the SESSION POOLER whenever the
// connection works. This is the fallback, not the default.
//
// USAGE
//   node scripts/bundle-migrations.mjs            # writes docs/_bundle.sql
// ============================================================================

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DOCS = join(ROOT, 'docs')
const OUT = join(DOCS, '_bundle.sql')

// Kept in step with run-migrations.mjs by reading it, rather than by copying
// the list — two lists that must match by hand are one edit away from silently
// disagreeing about the order DDL runs in.
const runner = readFileSync(join(ROOT, 'scripts', 'run-migrations.mjs'), 'utf8')
const orderBlock = /const ORDER = \[([\s\S]*?)\n\]/.exec(runner)

if (!orderBlock) {
  console.error('Could not read ORDER from run-migrations.mjs.')
  process.exit(1)
}

const ORDER = [...orderBlock[1].matchAll(/'([^']+\.sql)'/g)].map((match) => match[1])

/**
 * Files in `docs/` that are OUTPUT of this pipeline, not input to it.
 *
 * ⚠️ `SETUP-COMPLETE.sql` is this bundle plus a header, and it lives in
 * `docs/` without a leading underscore. A filter that only skipped `_` files
 * folded it back in — every table appeared twice and the bundle doubled in
 * size on each run. A generator that reads its own output compounds.
 */
const GENERATED = new Set(['SETUP-COMPLETE.sql'])

const present = readdirSync(DOCS).filter(
  (file) => file.endsWith('.sql') && !file.startsWith('_') && !GENERATED.has(file),
)

const ordered = [
  ...ORDER.filter((file) => present.includes(file)),
  ...present.filter((file) => !ORDER.includes(file)).sort(),
]

const parts = [
  '-- ============================================================================',
  '-- Hisabche — every migration, in order.',
  '--',
  '-- GENERATED by scripts/bundle-migrations.mjs. Do not edit; edit the source',
  '-- files in docs/ and regenerate.',
  '--',
  '-- Every statement is idempotent: CREATE TABLE IF NOT EXISTS, ADD COLUMN IF',
  '-- NOT EXISTS, DROP POLICY IF EXISTS before CREATE POLICY. Running this on a',
  '-- database that already holds data adds what is missing and changes nothing',
  '-- that is already correct. It does NOT drop anything.',
  '--',
  '-- Paste into the Supabase SQL Editor and run.',
  '-- ============================================================================',
  '',
]

const ledger = []

for (const file of ordered) {
  const sql = readFileSync(join(DOCS, file), 'utf8')
  const checksum = createHash('sha256').update(sql).digest('hex').slice(0, 16)

  parts.push(
    '',
    '-- ────────────────────────────────────────────────────────────────────────',
    `-- ${file}`,
    '-- ────────────────────────────────────────────────────────────────────────',
    '',
    sql.trim(),
    '',
  )

  ledger.push(`  ('${file}', '${checksum}', 'sql-editor')`)
}

// The ledger, so `run-migrations.mjs` knows these ran and does not offer them
// again. Without it the next person on a working connection would be told
// thirty migrations are pending against a database that already has them.
parts.push(
  '',
  '-- ────────────────────────────────────────────────────────────────────────',
  '-- Record what ran, so run-migrations.mjs agrees with reality.',
  '-- ────────────────────────────────────────────────────────────────────────',
  '',
  'CREATE TABLE IF NOT EXISTS schema_migrations (',
  '  name        text PRIMARY KEY,',
  '  checksum    text NOT NULL,',
  '  applied_at  timestamptz NOT NULL DEFAULT now(),',
  '  applied_by  text',
  ');',
  '',
  'INSERT INTO schema_migrations (name, checksum, applied_by) VALUES',
  `${ledger.join(',\n')}`,
  'ON CONFLICT (name) DO NOTHING;',
  '',
)

const bundle = parts.join('\n')
writeFileSync(OUT, bundle, 'utf8')

const kb = Math.round(bundle.length / 1024)

console.log(`Wrote docs/_bundle.sql — ${ordered.length} migrations, ${kb} KB.`)
console.log('')
console.log('Paste it into the Supabase SQL Editor and run. It creates and alters;')
console.log('it drops nothing. Take a backup first anyway.')

if (kb > 900) {
  console.log('')
  console.log(`NOTE: ${kb} KB may be more than the SQL Editor accepts in one paste.`)
  console.log('If it refuses, run the file in halves — the separators name each')
  console.log('migration, so split on a boundary and keep the order.')
}
