// ============================================
// Local SQLite schema — v3 (Offline Edition).
//
// Mirrors the server tables from @hisabche/db-schema, narrowed to what the
// desktop and mobile actually read and write offline.
//
// Rules:
// 1. Money columns are INTEGER (minor units: cents, pols, dinars).
// 2. Quantities are TEXT decimal (scale 4, matching numeric(18, 4)).
// 3. Every entity table carries workspace_id, id, created_at, updated_at,
//    deleted_at, origin, sync_state.
// 4. No hardcoded currency (AFN default removed).
// ============================================

